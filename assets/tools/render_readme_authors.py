"""Regenerate the light/dark outlined author assets (requires fonttools).

Uses Liberation Sans from the system; no font dependency is added to the package.
"""
from pathlib import Path
from xml.sax.saxutils import escape

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ASSETS_DIR = Path(__file__).resolve().parents[1]
FONT_DIR = Path('/usr/share/fonts/truetype')
ROWS = [
    [('Riccardo De Santi', '1,2,*'), ('Federico Di Gennaro', '1,*'), ('Angelo Gnazzo', '3,4,*')],
    [('Sophia Tang', '5'), ('Pranam Chatterjee', '5'), ('Fanny Yang', '1'),
     ('İsmail İlkan Ceylan', '3,4,6'), ('Michael M. Bronstein', '4,6'), ('Andreas Krause', '1,2')],
]


def font(name):
    return TTFont(next(FONT_DIR.rglob(name)))


def main():
    bold, regular = font('LiberationSans-Bold.ttf'), font('LiberationSans-Regular.ttf')
    spacing, gap = -0.65, 10
    def advance(text, face, size):
        cmap = face.getBestCmap()
        scale = size / face['head'].unitsPerEm
        return sum(face['hmtx'][cmap[ord(c)]][0]*scale+spacing for c in text)
    paths = []
    for index, row in enumerate(ROWS):
        width = sum(advance(name,bold,16)+advance(aff,regular,11) for name,aff in row)+gap*(len(row)-1)
        assert width <= 810, 'Author row exceeds the asset width'
        x, baseline = (820-width)/2, 18+24*index
        pen = SVGPathPen(None)
        for name, aff in row:
            for text, face, size, y in [(name,bold,16,baseline),(aff,regular,11,baseline-6)]:
                glyphs, cmap = face.getGlyphSet(), face.getBestCmap()
                pen.glyphSet = glyphs
                scale = size / face['head'].unitsPerEm
                for char in text:
                    glyphs[cmap[ord(char)]].draw(TransformPen(pen,(scale,0,0,-scale,x,y)))
                    x += advance(char,face,size)
            x += gap
        paths.append(f'    <path id="author-row-{index+1}" d="{pen.getCommands()}"/>')
    description = '; '.join(', '.join(f'{n} [{a}]' for n,a in row) for row in ROWS)
    for suffix, color in [('', '#1f2328'), ('-dark', '#f0f6fc')]:
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="820" height="48" viewBox="0 0 820 48" role="img" aria-labelledby="title description">
  <title id="title">Authors</title>
  <desc id="description">{escape(description)}</desc>
  <!-- Generated by assets/tools/render_readme_authors.py. Liberation Sans: 16px bold names,
       11px affiliation markers; identical letter spacing on both rows. -->
  <g fill="{color}">
{chr(10).join(paths)}
  </g>
</svg>
'''
        (ASSETS_DIR/f'authors-outlined{suffix}.svg').write_text(svg)


if __name__ == '__main__':
    main()
